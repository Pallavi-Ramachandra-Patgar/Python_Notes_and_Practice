# WHILE LOOP:
'''Syntax:
while(condition):
The block keep executing until the condition is true body of the loop

In while loops, the condition is checked first.if it evaluates a true, the body of the loop 
is executed otehrwise not

if the loop is entered, the process of[condition check & execution] is continued until the
condition becomes False'''

i = 1
while(i<6):
    print(i)
    i +=1

'''output: 1,2,3,4,5'''

